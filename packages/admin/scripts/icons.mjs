// Writes core's `IconName` type from the icon files of the installed `@lucide/vue`. Run after updating it.
import { readdirSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";

const require = createRequire(import.meta.url);
const dir = join(dirname(require.resolve("@lucide/vue/package.json")), "dist/esm/icons");
const names = readdirSync(dir)
  .filter((f) => f.endsWith(".mjs") && f !== "index.mjs")
  .map((f) => f.slice(0, -4))
  .sort();

const out = new URL("../../core/src/admin/icons.d.ts", import.meta.url);
writeFileSync(
  out,
  `// Generated by packages/admin/scripts/icons.mjs from @lucide/vue. Do not edit.\n/** Name of a Lucide icon, e.g. \`arrow-right-left\`. See https://lucide.dev/icons. */\nexport type IconName =\n${names.map((n) => `  | "${n}"`).join("\n")};\n`,
);
console.log(`${names.length} icons`);
