// Bundles drizzle-kit SQL output into a TS module so migrations run without a filesystem.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'

const dir = new URL('../drizzle/', import.meta.url)
const migrations = readdirSync(dir)
  .filter((f) => f.endsWith('.sql'))
  .sort()
  .map((f) => ({ name: f, sql: readFileSync(new URL(f, dir), 'utf8') }))

writeFileSync(
  new URL('../src/db/migrations.gen.ts', import.meta.url),
  `// Generated by scripts/embed-migrations.mjs. Do not edit.\nexport default ${JSON.stringify(migrations, null, 2)}\n`,
)
console.log(`embedded ${migrations.length} migration(s)`)
